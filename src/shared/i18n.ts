import { Language } from './types';

export function detectBrowserLanguage(rawLang: string | null | undefined): Language {
  if (!rawLang) return 'tr';
  const primary = rawLang.trim().toLowerCase().split(',')[0]?.split('-')[0];
  if (primary === 'en') return 'en';
  if (primary === 'tr') return 'tr';
  return 'tr';
}

export function resolveLocalizedText(
  trValue: string | null | undefined,
  enValue: string | null | undefined,
  lang: Language,
  fallbackLang: Language = 'tr'
): string {
  const tr = (trValue ?? '').trim();
  const en = (enValue ?? '').trim();
  if (lang === 'en') {
    return en || (fallbackLang === 'tr' ? tr : '') || tr;
  }
  return tr || (fallbackLang === 'en' ? en : '') || en;
}

